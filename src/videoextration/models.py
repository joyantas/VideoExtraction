"""Public request models and provider contracts."""

from pathlib import Path
from typing import Any, Literal, Protocol

from pydantic import BaseModel, ConfigDict, Field


FindingState = Literal["pass", "fail", "needs-review", "not-evaluated"]
JobState = Literal["awaiting-upload", "uploading", "uploaded", "queued", "processing", "completed", "failed"]
ALLOWED_CONTENT_TYPES = {"video/mp4", "video/quicktime", "video/webm", "video/x-matroska", "video/x-msvideo"}


class CreateJob(BaseModel):
    model_config = ConfigDict(extra="forbid", str_strip_whitespace=True)
    filename: str = Field(min_length=1, max_length=255)
    content_type: str
    size_bytes: int = Field(gt=0)
    required_text: list[str] = Field(default_factory=list, max_length=20)
    profile: Literal["illustrative-portrait-v1"] = "illustrative-portrait-v1"


class AuthProvider(Protocol):
    def __call__(self, bearer_token: str) -> str:
        """Return a stable owner ID after verifying identity, or raise ValueError."""
        ...


class BlobProvider(Protocol):
    def path_for(self, job_id: str, *, partial: bool = False) -> Path: ...
    def materialize(self, job_id: str) -> Path: ...
    def commit(self, job_id: str) -> None: ...
    def discard(self, job_id: str) -> None: ...
    def ready(self) -> bool: ...


class AnalysisProvider(Protocol):
    def analyze(self, path: Path) -> dict[str, Any]: ...


class SemanticProvider(Protocol):
    def evaluate(self, path: Path, required_text: list[str]) -> dict[str, Any]:
        """Optional external AI/OCR hook; must return evidence, coverage and findings."""
        ...


class JobRepository(Protocol):
    def ready(self) -> bool: ...
    def create(self, owner: str, request: dict, token_hash: str, expires: float) -> dict: ...
    def get(self, job_id: str, owner: str | None = None) -> dict | None: ...
    def begin_upload(self, job_id: str, token_hash: str, now: float) -> dict | None: ...
    def finish_upload(self, job_id: str, size: int, sha256: str) -> None: ...
    def fail_upload(self, job_id: str) -> None: ...
    def finalize(self, job_id: str, owner: str) -> dict | None: ...
    def claim(self, lease_seconds: int) -> dict | None: ...
    def complete(self, job_id: str, lease_id: str, report: dict) -> bool: ...
    def fail(self, job_id: str, lease_id: str, report: dict) -> bool: ...
